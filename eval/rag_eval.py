"""Evaluate retrieval and answers on eval/questions.jsonl.

    python -m eval.rag_eval                          # offline extractive answerer (free, deterministic)
    python -m eval.rag_eval --provider anthropic     # Claude; needs ANTHROPIC_API_KEY and costs a little
    python -m eval.rag_eval --check                  # CI: exit 1 if extractive scores fall below the floors

The questions were written by hand against the four synthetic policy documents while
building this project, so treat the scores as a regression check, not a benchmark.

Writes reports/rag_eval_<provider>.json and refreshes reports/rag_eval.md.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict, replace
from pathlib import Path

from app.answer import PolicyQA, build_answerer
from app.config import ROOT, Settings
from app.documents import load_chunks
from app.retrieval import Retriever

QUESTIONS = ROOT / "eval" / "questions.jsonl"
REPORTS = ROOT / "reports"

# Floors for --check (offline extractive answerer). Set a little below the measured scores.
FLOORS = {"retrieval_hit_at_3": 0.90, "answer_accuracy": 0.85, "not_found_accuracy": 0.375}


def load_questions(path: Path = QUESTIONS) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def matches(text: str, groups: list[list[str]]) -> bool:
    lowered = text.lower()
    return all(any(alt.lower() in lowered for alt in group) for group in groups)


def run(provider: str, settings: Settings | None = None) -> dict:
    settings = replace(settings or Settings.from_env(), llm_provider=provider)
    retriever = Retriever(load_chunks(settings.docs_dir))
    answerer = build_answerer(settings, retriever)
    qa = PolicyQA(retriever, answerer, top_k=settings.top_k, min_score=settings.min_retrieval_score)

    rows = []
    for q in load_questions():
        start = time.perf_counter()
        answer, hits = qa.ask(q["question"])
        latency = time.perf_counter() - start
        top_sources = [h.chunk.source_file for h in hits]
        row = {
            "id": q["id"],
            "question": q["question"],
            "expect": q["expect"],
            "found": answer.found,
            "answer": answer.text,
            "citations": [asdict(c) for c in answer.citations],
            "top_chunks": [(h.chunk.chunk_id, h.score) for h in hits],
            "fallback_reason": answer.fallback_reason,
            "usage": answer.usage,
            "latency_ms": round(latency * 1000, 1),
        }
        if q["expect"] == "answer":
            sources = set(q["sources"])
            row["hit_at_1"] = bool(top_sources[:1]) and top_sources[0] in sources
            row["hit_at_3"] = bool(sources & set(top_sources[:3]))
            row["correct"] = answer.found and matches(answer.text, q["must_include"])
            row["cites_expected_source"] = answer.found and any(c.source_file in sources for c in answer.citations)
        else:
            row["correct"] = not answer.found
        rows.append(row)

    answerable = [r for r in rows if r["expect"] == "answer"]
    unanswerable = [r for r in rows if r["expect"] == "not_found"]

    def rate(items, key):
        return round(sum(bool(r[key]) for r in items) / len(items), 3) if items else None

    latencies = sorted(r["latency_ms"] for r in rows)
    summary = {
        "provider": qa.provider,
        "questions": len(rows),
        "answerable": len(answerable),
        "unanswerable": len(unanswerable),
        "retrieval_hit_at_1": rate(answerable, "hit_at_1"),
        "retrieval_hit_at_3": rate(answerable, "hit_at_3"),
        "answer_accuracy": rate(answerable, "correct"),
        "cites_expected_source": rate(answerable, "cites_expected_source"),
        "false_not_found": round(sum(not r["found"] for r in answerable) / len(answerable), 3),
        "not_found_accuracy": rate(unanswerable, "correct"),
        "llm_fallbacks": sum(1 for r in rows if r["fallback_reason"]),
        "median_latency_ms": latencies[len(latencies) // 2],
        "input_tokens": sum(r["usage"].get("input_tokens", 0) for r in rows),
        "output_tokens": sum(r["usage"].get("output_tokens", 0) for r in rows),
    }
    return {"summary": summary, "rows": rows}


def slug(provider: str) -> str:
    return provider.split("/")[0]


def write_reports(result: dict) -> None:
    REPORTS.mkdir(exist_ok=True)
    path = REPORTS / f"rag_eval_{slug(result['summary']['provider'])}.json"
    path.write_text(json.dumps(result, indent=2) + "\n")

    summaries = []
    for p in sorted(REPORTS.glob("rag_eval_*.json")):
        summaries.append(json.loads(p.read_text())["summary"])
    lines = [
        "# Policy Q&A evaluation",
        "",
        "Generated by `python -m eval.rag_eval`. 40 hand-written questions over the four synthetic policy",
        "documents in `data/policy_documents/`: 32 the documents answer and 8 they don't. I wrote the",
        "questions while building the project, so this is a regression check, not a benchmark.",
        "",
        "| Metric | " + " | ".join(f"`{s['provider']}`" for s in summaries) + " |",
        "|---|" + "---|" * len(summaries),
    ]
    metrics = [
        ("Right document in top 1 (retrieval)", "retrieval_hit_at_1", "pct"),
        ("Right document in top 3 (retrieval)", "retrieval_hit_at_3", "pct"),
        ("Answer contains the expected fact", "answer_accuracy", "pct"),
        ("Answer cites the expected document", "cites_expected_source", "pct"),
        ("Answerable question answered 'not found'", "false_not_found", "pct"),
        ("Unanswerable question answered 'not found'", "not_found_accuracy", "pct"),
        ("LLM answers replaced by the extractive fallback", "llm_fallbacks", "int"),
        ("Median time per question (ms)", "median_latency_ms", "float"),
        ("Input / output tokens (whole run)", None, "tokens"),
    ]
    for label, key, kind in metrics:
        cells = []
        for s in summaries:
            if kind == "pct":
                cells.append(f"{s[key]:.0%}")
            elif kind == "int":
                cells.append(str(s[key]))
            elif kind == "float":
                cells.append(f"{s[key]:,.0f}" if s[key] >= 10 else f"{s[key]:.1f}")
            else:
                cells.append(f"{s['input_tokens']:,} / {s['output_tokens']:,}" if s["input_tokens"] else "-")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "Per-question answers are in the matching `rag_eval_<provider>.json` file.",
        "",
    ]
    (REPORTS / "rag_eval.md").write_text("\n".join(lines))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--provider", default="extractive", choices=["extractive", "anthropic", "azure_openai"])
    parser.add_argument("--check", action="store_true", help="exit 1 if extractive scores fall below FLOORS")
    parser.add_argument("--no-write", action="store_true", help="don't write reports/")
    args = parser.parse_args(argv)

    result = run(args.provider)
    s = result["summary"]
    print(json.dumps(s, indent=2))
    for r in result["rows"]:
        if not r["correct"]:
            print(f"  miss {r['id']}: {r['question']} -> {r['answer'][:120]!r}")
    if not args.no_write:
        write_reports(result)

    if args.check:
        if args.provider != "extractive":
            print("--check only applies to the extractive provider")
            return 2
        failed = {k: s[k] for k, floor in FLOORS.items() if s[k] < floor}
        if failed:
            print(f"FAIL: below floors {FLOORS}: {failed}")
            return 1
        print(f"OK: all metrics at or above floors {FLOORS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
